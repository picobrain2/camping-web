#!/usr/bin/env python3
"""Build packs/gyeonggi.json and patch layout images + review quotes on existing camps."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "public" / "data"


def compact(text: str) -> str:
    return "".join(ch for ch in text.lower() if ch.isalnum() or "\uac00" <= ch <= "\ud7a3")


def load_existing():
    index = json.loads((DATA / "index.json").read_text(encoding="utf-8"))
    ids, names = set(), set()
    files = [DATA / pack for pack in index["packs"]]
    for path in files:
        if not path.exists():
            continue
        payload = json.loads(path.read_text(encoding="utf-8"))
        for camp in payload.get("camps", []):
            if camp.get("id"):
                ids.add(camp["id"])
            if camp.get("name"):
                names.add(compact(camp["name"]))
            for alias in camp.get("aliases") or []:
                names.add(compact(alias))
    return ids, names, files


def camp_row(cid, name, aliases, city, address, kinds, tags, desc, extra=None):
    extra = extra or {}
    price = extra.get("price", (40000, 80000))
    rating = extra.get("rating", 4.3)
    kind_name = (
        "글램핑" if "glamping" in kinds and "auto" not in kinds
        else "카라반" if "caravan" in kinds and "auto" not in kinds
        else "오토캠핑"
    )
    camp = {
        "id": cid,
        "name": name,
        "aliases": aliases,
        "region": "경기",
        "city": city,
        "kinds": kinds,
        "tags": tags,
        "address": address,
        "reservationPlatform": extra.get("platform", "캠핏 · 네이버 · 전화"),
        "reservationWindows": [
            {"label": "상시", "rule": extra.get("rule", "캠핏·네이버·전화로 빈자리와 배치도를 확인하세요.")}
        ],
        "siteTypes": [{"name": kind_name, "priceMin": price[0], "priceMax": price[1]}],
        "amenities": extra.get("amenities", ["화장실", "샤워장", "개수대", "전기"]),
        "description": desc,
        "ratings": {"naver": rating},
    }
    if extra.get("phone"):
        camp["phone"] = extra["phone"]
    if extra.get("homepage"):
        camp["homepage"] = extra["homepage"]
    if extra.get("layoutImage"):
        camp["layoutImage"] = extra["layoutImage"]
    if extra.get("quotes"):
        camp["quotes"] = extra["quotes"]
    if extra.get("featured"):
        camp["featured"] = True
    return camp


