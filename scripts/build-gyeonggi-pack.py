def patch_existing(files):
    changed = 0
    for path in files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        dirty = False
        for camp in payload.get("camps", []):
            cid = camp.get("id")
            if cid in LAYOUT_IMAGES:
                camp["layoutImage"] = LAYOUT_IMAGES[cid]
                if str(camp.get("layoutUrl", "")).find("camppick.com") >= 0:
                    camp.pop("layoutUrl", None)
                dirty = True
            if cid in QUOTES_BY_ID and not camp.get("quotes"):
                camp["quotes"] = QUOTES_BY_ID[cid]
                dirty = True
        if dirty:
            path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            changed += 1
    return changed


