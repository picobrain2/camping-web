def row_to_camp(row):
    cid, name, aliases, region, city, kinds, tags, address, phone, desc, extra = row
    price = extra.get("price", (40000, 70000))
    camp = {
        "id": cid,
        "name": name,
        "aliases": aliases,
        "region": region,
        "city": city,
        "kinds": kinds,
        "tags": tags,
        "address": address,
        "reservationPlatform": extra.get("reservationPlatform", "캠프픽 · 캠핏 · 네이버"),
        "reservationWindows": [{"label": "상시", "rule": "캠프픽·캠핏·네이버에서 배치도와 빈자리를 확인하세요."}],
        "siteTypes": [{"name": "오토캠핑" if "auto" in kinds else ("글램핑" if "glamping" in kinds else ("카라반" if "caravan" in kinds else "일반야영")),
                       "priceMin": price[0], "priceMax": price[1]}],
        "amenities": ["화장실", "샤워장", "개수대", "전기"],
        "description": desc,
        "ratings": {"naver": 4.3},
    }
    if phone:
        camp["phone"] = phone
    for key in ("homepage", "reservationUrl", "layoutUrl"):
        if key in extra:
            camp[key] = extra[key]
    if extra.get("featured"):
        camp["featured"] = True
    return camp


def main():
    camps = [row_to_camp(r) for r in ROWS]
    if len(camps) < 100:
        raise SystemExit(f"expected at least 100 camps, got {len(camps)}")
    ids = [c["id"] for c in camps]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate ids in hit pack")
    out = {
        "updatedAt": "2026-09-04",
        "note": "캠프픽·땡큐캠핑·고캠핑·지역 추천에 반복되는 인기 캠핑 100곳.",
        "camps": camps,
    }
    dest = Path(__file__).resolve().parents[1] / "public/data/packs/hit.json"
    dest.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(camps)} camps -> {dest}")


if __name__ == "__main__":
    main()
